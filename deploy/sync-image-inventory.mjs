/**
 * Rebuild src/data/imageInventory.generated.ts from public/images.
 * Runs before dev/build so factory/product pages follow files on disk,
 * not a stale committed inventory.
 */
import { createHash } from 'node:crypto';
import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'public');
const IMAGES = join(PUBLIC, 'images');
const DEST = join(ROOT, 'src', 'data', 'imageInventory.generated.ts');
const PRODUCT_ORDER = [
  'main.webp',
  'catalog.webp',
  'working.webp',
  'working-2.webp',
];

function listWebp(dir, prefix) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.toLowerCase().endsWith('.webp'))
    .sort()
    .map((name) => `${prefix}/${name}`);
}

function tsList(paths) {
  if (!paths.length) return '[]';
  return `[\n${paths.map((path) => `  ${JSON.stringify(path)},`).join('\n')}\n]`;
}

function walkFiles(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) walkFiles(full, acc);
    else acc.push(full);
  }
  return acc;
}

const factory = listWebp(join(IMAGES, 'factory'), '/images/factory');
const applications = listWebp(
  join(IMAGES, 'applications'),
  '/images/applications',
);
const hero = listWebp(join(IMAGES, 'hero'), '/images/hero');

const products = {};
const productsRoot = join(IMAGES, 'products');
if (existsSync(productsRoot)) {
  for (const folder of readdirSync(productsRoot).sort()) {
    const dir = join(productsRoot, folder);
    if (!statSync(dir).isDirectory()) continue;
    const files = readdirSync(dir).filter((name) =>
      name.toLowerCase().endsWith('.webp'),
    );
    files.sort((a, b) => {
      const ia = PRODUCT_ORDER.indexOf(a);
      const ib = PRODUCT_ORDER.indexOf(b);
      const sa = ia === -1 ? PRODUCT_ORDER.length : ia;
      const sb = ib === -1 ? PRODUCT_ORDER.length : ib;
      return sa === sb ? a.localeCompare(b) : sa - sb;
    });
    products[folder] = files.map((name) => `/images/products/${folder}/${name}`);
  }
}

const revs = {};
for (const path of walkFiles(IMAGES).sort()) {
  const ext = path.toLowerCase().slice(path.lastIndexOf('.'));
  if (!['.webp', '.svg', '.png'].includes(ext)) continue;
  const rel = `/${relative(PUBLIC, path).replaceAll('\\', '/')}`;
  revs[rel] = createHash('md5').update(readFileSync(path)).digest('hex').slice(0, 10);
}

const productEntries = Object.entries(products).map(([slug, paths]) => {
  const inner = paths.map((path) => `    ${JSON.stringify(path)},`).join('\n');
  return `  ${JSON.stringify(slug)}: [\n${inner}\n  ]`;
});
const productBlock = productEntries.length
  ? `{\n${productEntries.join(',\n')},\n}`
  : '{}';

const revEntries = Object.entries(revs).map(
  ([rel, rev]) => `  ${JSON.stringify(rel)}: ${JSON.stringify(rev)}`,
);
const revBlock = revEntries.length ? `{\n${revEntries.join(',\n')},\n}` : '{}';

const text =
  '/* Generated by deploy/generate_sitemaps.py — do not edit by hand. */\n' +
  `export const factoryPublicImages = ${tsList(factory)} as const;\n\n` +
  `export const applicationPublicImages = ${tsList(applications)} as const;\n\n` +
  `export const heroPublicImages = ${tsList(hero)} as const;\n\n` +
  `export const productPublicImagesBySlug: Record<string, readonly string[]> = ${productBlock};\n\n` +
  `export const publicImageRev: Record<string, string> = ${revBlock};\n`;

writeFileSync(DEST, text, 'utf8');
console.log(
  `wrote src/data/imageInventory.generated.ts factory=${factory.length} products=${Object.keys(products).length}`,
);
